import { BadRequestException, Injectable, NotFoundException } from '@nestjs/common';
import { Prisma } from '@prisma/client';
import { PrismaService } from '../prisma/prisma.service';

export interface CreateExternalReportInput {
  bullets: string[];
  prs?: Array<{ repo: string; title: string; commits?: string[] }>;
  prCount?: number;
  commitCount?: number;
  modelName?: string;
  dateRangeStart?: Date;
  dateRangeEnd?: Date;
  taskIds?: string[];
}

@Injectable()
export class ReportsService {
  constructor(private readonly prisma: PrismaService) {}

  async listReports(userId: string) {
    return this.prisma.reportHistory.findMany({
      where: { userId },
      orderBy: { createdAt: 'desc' },
      take: 50,
    });
  }

  async getReportById(userId: string, id: string) {
    const report = await this.prisma.reportHistory.findFirst({
      where: { id, userId },
    });
    if (!report) {
      throw new NotFoundException('Không tìm thấy bản báo cáo.');
    }
    return report;
  }

  /** Persists a pre-summarized standup report generated by an external MCP agent. */
  async createExternalReport(userId: string, input: CreateExternalReportInput) {
    const cleanBullets = input.bullets.map((b) => b.trim()).filter((b) => b.length > 0);
    if (cleanBullets.length === 0) {
      throw new BadRequestException('Nội dung báo cáo phải có ít nhất một gạch đầu dòng.');
    }

    const prs = input.prs ?? [];
    const computedCommitCount = prs.reduce((acc, pr) => acc + (pr.commits?.length ?? 0), 0);
    const now = new Date();
    const startOfDay = new Date(now);
    startOfDay.setHours(0, 0, 0, 0);

    return this.prisma.reportHistory.create({
      data: {
        userId,
        summaryText: cleanBullets.map((b) => `• ${b}`).join('\n'),
        prCount: input.prCount ?? prs.length,
        commitCount: input.commitCount ?? computedCommitCount,
        aiEngineUsed: 'MCP_AGENT',
        modelName: (input.modelName || 'external-mcp-agent').trim().slice(0, 120),
        metadata: JSON.parse(
          JSON.stringify({
            prs,
            ...(input.taskIds && input.taskIds.length > 0 ? { taskIds: input.taskIds } : {}),
          }),
        ) as Prisma.InputJsonValue,
        dateRangeStart: input.dateRangeStart ?? startOfDay,
        dateRangeEnd: input.dateRangeEnd ?? now,
      },
    });
  }

  async deleteReport(userId: string, id: string) {
    await this.prisma.reportHistory.deleteMany({
      where: { id, userId },
    });
    return { success: true };
  }
}
